/**
 * Searches curated and stock APIs based on natural language query, category or tags.
 */
export function searchStockPhotos(query: string, categoryFilter?: string): StockPhotoAsset[] {
  const cleanQ = (query || "").toLowerCase().trim();
  const cleanCat = (categoryFilter || "").toLowerCase().trim();

  let matches = CURATED_STOCK_CATALOG;

  if (cleanCat && cleanCat !== "all") {
    matches = matches.filter(
      (item) => item.category === cleanCat || item.tags.some((t) => t.includes(cleanCat))
    );
  }

  if (!cleanQ) {
    return matches;
  }

  const queryTerms = cleanQ.split(/\s+/).filter((t) => t.length > 1);

  return matches
    .map((item) => {
      let score = 0;
      for (const term of queryTerms) {
        if (item.category.includes(term)) score += 10;
        if (item.title.toLowerCase().includes(term)) score += 5;
        if (item.tags.some((t) => t.includes(term))) score += 4;
      }
      return { item, score };
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.item);
}

/**
 * Automatically resolves the optimal stock photo for a business brief
 */
export function resolveBestStockPhoto(
  categoryName: string,
  headline: string,
  customUrl?: string
): StockPhotoAsset {
  if (customUrl) {
    const existing = CURATED_STOCK_CATALOG.find((p) => p.url === customUrl);
    if (existing) return existing;
    return {
      id: "custom_stock_" + Math.random().toString(36).substring(7),
      title: "Selected Custom Stock Photography",
      url: customUrl,
      thumbUrl: customUrl,
      author: "Verified Commercial Stock",
      source: "curated",
      category: categoryName || "general",
      tags: [categoryName || "commercial"],
      width: 1200,
      height: 800,
      focalPoint: { x: 0.5, y: 0.5 },
    };
  }

  const combinedSearch = `${categoryName} ${headline}`;
  const searchResults = searchStockPhotos(combinedSearch, categoryName);
  if (searchResults.length > 0) {
    return searchResults[0];
  }

  // Fallback to primary category matches
  const catMatches = searchStockPhotos("", categoryName);
  if (catMatches.length > 0) {
    return catMatches[0];
  }

  return CURATED_STOCK_CATALOG[0];
}
